// `work` runs a pipeline and routes to `review`; `review` is manual so the
// ticket stops there with its pack in place.
const routingDefinition = {
  name: "routing-packs",
  lanes: [
    {
      key: "work",
      name: "Work",
      entry: "auto",
      pipeline: [
        {
          key: "code",
          type: "agent",
          agent: { instance: "claude_main", model: "sonnet" },
          instruction: "do it",
        },
      ],
      on: { success: "review" },
    },
    { key: "review", name: "Review", entry: "manual" },
    { key: "done", name: "Done", entry: "manual", terminal: true },
  ],
};

const awaitLane = (ticketId: string, laneKey: string) =>
  Effect.gen(function* () {
    const read = yield* WorkflowReadModel;
    for (let attempt = 0; attempt < 100; attempt += 1) {
      const detail = yield* read.getTicketDetail(ticketId as never);
      if (detail?.ticket.currentLaneKey === laneKey) {
        return detail;
      }
      yield* Effect.promise<void>(() => new Promise((resolve) => setTimeout(resolve, 10)));
      yield* Effect.yieldNow;
    }
    return yield* read.getTicketDetail(ticketId as never);
  });

compilingLayer("WorkflowEngine context pack routing", (it) => {
  it.effect("commits the pack event LAST in the routed batch and stores it for the new lane", () =>
    Effect.gen(function* () {
      const registry = yield* BoardRegistry;
      yield* registry.register("b-route-pack" as never, routingDefinition);
      const engine = yield* WorkflowEngine;
      const read = yield* WorkflowReadModel;
      const store = yield* WorkflowEventStore;

      const ticket = yield* engine.createTicket({
        boardId: "b-route-pack" as never,
        title: "Routed",
        initialLane: "work" as never,
      });
      yield* awaitLane(ticket, "review");

      const events = yield* Stream.runCollect(store.readByTicket(ticket)).pipe(
        Effect.map((chunk) => Array.from(chunk)),
      );
      const types = events.map((event) => event.type);
      const packIndex = types.indexOf("TicketContextPackCompiled");
      assert.isAbove(packIndex, -1, "routing must compile a pack");
      // Pack LAST: the move fold clears the destination pack, so only a trailing
      // pack event survives into the projection.
      assert.deepStrictEqual(types.slice(packIndex - 2, packIndex + 1), [
        "TicketRouteDecided",
        "TicketMovedToLane",
        "TicketContextPackCompiled",
      ]);

      const pack = yield* read.getContextPack(ticket, "review" as never);
      assert.equal(pack?.fromLane, "work");
      assert.deepStrictEqual(pack?.sections, [
        { key: "notes", body: "compiled by the stub", autoGenerated: true },
      ]);
    }),
  );

  it.effect("a manual move compiles nothing and clears the destination's pack", () =>
    Effect.gen(function* () {
      const registry = yield* BoardRegistry;
      yield* registry.register("b-manual-clear" as never, routingDefinition);
      const engine = yield* WorkflowEngine;
      const read = yield* WorkflowReadModel;

      const ticket = yield* engine.createTicket({
        boardId: "b-manual-clear" as never,
        title: "Manual",
        initialLane: "work" as never,
      });
      yield* awaitLane(ticket, "review");
      assert.isNotNull(yield* read.getContextPack(ticket, "review" as never));

      // Move away and back by hand: the manual entry must leave no pack behind.
      yield* engine.moveTicket(ticket, "done" as never);
      yield* engine.moveTicket(ticket, "review" as never);
      assert.isNull(yield* read.getContextPack(ticket, "review" as never));
    }),
  );
});
